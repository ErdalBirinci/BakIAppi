function currentLang() {
  const stored = localStorage.getItem(I18N_KEY);
  return I18N_LANGS.includes(stored) ? stored : "tr";
}

/* Belirli bir dilde metin (kart açıklaması kart dilini izler). */
function tIn(lang, key, vars) {
  const dict = I18N[lang] || I18N.tr;
  let text = dict[key] ?? I18N.tr[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.replaceAll(`{${name}}`, String(value));
    });
  }
  return text;
}

function t(key, vars) {
  return tIn(currentLang(), key, vars);
}

const SERVER_ERROR_KEYS = {
  "Kullanıcı adı veya şifre hatalı.": "err.badLogin",
  "Bu kullanıcı adı zaten alınmış.": "err.duplicateUser",
  "Şifre en az 6 karakter olmalı.": "err.shortPassword",
  "Kullanıcı adı en az 3 karakter olmalı.": "err.shortUsername",
  "Grup adı en az 2 karakter olmalı.": "err.shortGroup",
  "Giriş gerekli.": "err.session",
};

/* Sunucudan gelen Türkçe hata metnini seçili dile çevirir. */
function serverMessage(message) {
  const key = SERVER_ERROR_KEYS[String(message).trim()];
  return key ? t(key) : String(message);
}

const CARD_LANG_KEY = "bakiappi-card-lang";
const CARD_LANGS = ["fi", "en"];

/* Kart dili ayrı seçilir; seçilmediyse arayüz dilini izler (TR → FI). */
function cardLang() {
  const stored = localStorage.getItem(CARD_LANG_KEY);
  if (CARD_LANGS.includes(stored)) return stored;
  return currentLang() === "en" ? "en" : "fi";
}

function applyLang(lang) {
  const next = I18N_LANGS.includes(lang) ? lang : "tr";
  localStorage.setItem(I18N_KEY, next);
  document.documentElement.lang = next;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("select[data-lang-select]").forEach((select) => {
    select.value = next;
  });
  document.querySelectorAll("select[data-card-lang]").forEach((select) => {
    select.value = cardLang();
  });
  document.dispatchEvent(new CustomEvent("i18n:changed", { detail: { lang: next } }));
}

function fillSelect(select, values, value) {
  select.innerHTML = values
    .map((code) => `<option value="${code}">${code.toUpperCase()}</option>`)
    .join("");
  select.value = value;
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("select[data-lang-select]").forEach((select) => {
    fillSelect(select, I18N_LANGS, currentLang());
    select.setAttribute("aria-label", t("common.language"));
    select.addEventListener("change", () => applyLang(select.value));
  });
  document.querySelectorAll("select[data-card-lang]").forEach((select) => {
    fillSelect(select, CARD_LANGS, cardLang());
    select.setAttribute("aria-label", t("cards.lang"));
    select.addEventListener("change", () => {
      localStorage.setItem(CARD_LANG_KEY, select.value);
      document.dispatchEvent(
        new CustomEvent("cardlang:changed", { detail: { lang: select.value } })
      );
    });
  });
  applyLang(currentLang());
});
